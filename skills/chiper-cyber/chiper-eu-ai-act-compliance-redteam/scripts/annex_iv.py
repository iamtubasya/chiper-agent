#!/usr/bin/env python3
"""Generate the Annex IV technical documentation file (Markdown + JSON).

Documented usage (chiper-eu-ai-act-compliance-redteam SKILL.md, Phase 4):

    python3 scripts/annex_iv.py \
      --risk-register risks.json \
      --test-evidence evidence/ \
      --model-card model_card.json \
      --datasheet data/datasheet.yaml \
      --output annex_iv_technical_file.md
"""
import argparse
import json
import os
import sys
from pathlib import Path

ITEMS = [
    (1, "System description", "General description, intended purpose, provider, "
                              "interaction with other systems."),
    (2, "Design choices", "Design choices, assumptions and human-oversight measures."),
    (3, "Monitoring", "Monitoring, functioning and control capabilities, anomaly response."),
    (4, "Validation", "Pre-market validation and testing procedures with metrics."),
    (5, "Risk management", "Risk management system across the lifecycle (Art. 9)."),
    (6, "Lifecycle changes", "Changes through the lifecycle, data governance, retraining."),
    (7, "Standards", "Harmonised standards applied or solutions adopted."),
    (8, "EU declaration", "EU declaration of conformity and relevant certificates."),
    (9, "Post-market", "Post-market monitoring plan and event-logging for traceability."),
    (10, "Other information", "Any other information required by the assessment procedure."),
]


def load_structured(path: Path):
    """Read JSON or YAML (PyYAML optional) into a dict; return None when absent."""
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8", errors="replace")
    if path.suffix.lower() == ".json":
        try:
            return json.loads(text)
        except json.JSONDecodeError as exc:
            raise SystemExit(f"error: {path} is not valid JSON: {exc}")
    try:
        import yaml  # type: ignore
        return yaml.safe_load(text)
    except ImportError:
        # minimal fallback: flatten top-level "key: value" pairs
        flat = {}
        for line in text.splitlines():
            if ":" in line and not line.lstrip().startswith(("#", "-", " ")):
                k, _, v = line.partition(":")
                flat[k.strip()] = v.strip().strip('"').strip("'")
        return flat


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate the Annex IV technical file.")
    ap.add_argument("--risk-register", help="JSON/YAML risk register from Phase 2")
    ap.add_argument("--test-evidence", help="directory holding Phase 3 evidence")
    ap.add_argument("--model-card", help="JSON model card from Phase 4")
    ap.add_argument("--datasheet", help="datasheet YAML from Phase 4")
    ap.add_argument("--output", required=True, help="Markdown file to write")
    ap.add_argument("--json", dest="json_out", help="also write machine-readable JSON")
    args = ap.parse_args()

    risks = load_structured(Path(args.risk_register)) if args.risk_register else None
    card = load_structured(Path(args.model_card)) if args.model_card else None
    sheet = load_structured(Path(args.datasheet)) if args.datasheet else None

    evidence_files = []
    if args.test_evidence:
        root = Path(args.test_evidence)
        if not root.exists():
            print(f"error: evidence dir {root} not found", file=sys.stderr)
            return 2
        evidence_files = sorted(str(p) for p in root.rglob("*") if p.is_file())

    risk_rows = []
    if isinstance(risks, dict):
        entries = risks.get("risks") or risks.get("entries") or []
    elif isinstance(risks, list):
        entries = risks
    else:
        entries = []
    for entry in entries if isinstance(entries, list) else []:
        if isinstance(entry, dict):
            risk_rows.append((entry.get("id", "-"), entry.get("title", entry.get("risk", "-")),
                              entry.get("severity", entry.get("rating", "-"))))

    name = (sheet or {}).get("system", {}).get("name") if isinstance(sheet, dict) else None
    if not name and isinstance(card, dict):
        name = card.get("name") or card.get("model")
    name = name or "unnamed AI system"

    lines = [f"# Annex IV technical documentation — {name}", "",
             "Generated by `scripts/annex_iv.py` (chiper-eu-ai-act-compliance-redteam).", ""]
    for n, title, req in ITEMS:
        lines.append(f"## {n}. {title}")
        lines.append("")
        lines.append(req)
        lines.append("")
        if n == 5 and risk_rows:
            lines.append("| Risk ID | Title | Severity |")
            lines.append("|---|---|---|")
            lines += [f"| {i} | {t} | {s} |" for i, t, s in risk_rows]
            lines.append("")
        if n == 4 and evidence_files:
            lines.append("Evidence reviewed:")
            lines += [f"- `{f}`" for f in evidence_files[:40]]
            lines.append("")
        if n == 6 and isinstance(sheet, dict):
            models = (sheet.get("models") or [])
            for m in models if isinstance(models, list) else []:
                if isinstance(m, dict):
                    mname = m.get("name", "?")
                    mtype = m.get("type", "?")
                    lims = ", ".join(m.get("known_limitations", [])) or "n/a"
                    lines.append(f"- `{mname}` ({mtype}) - limitations: {lims}")
        if n == 9 and isinstance(card, dict) and card.get("post_market"):
            lines.append(str(card["post_market"]))
            lines.append("")

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(lines)} lines)")

    if args.json_out:
        doc = {"system": name, "annex_iv": [{"item": n, "title": t, "requirement": d}
                                            for n, t, d in ITEMS],
               "risks": risk_rows, "evidence": evidence_files}
        Path(args.json_out).write_text(json.dumps(doc, indent=2), encoding="utf-8")
        print(f"wrote {args.json_out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
