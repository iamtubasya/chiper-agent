#!/usr/bin/env python3
"""Build a MITRE ATT&CK Navigator layer from technique ids.

Usage:
    python3 scripts/build-navigator-layer.py t1059 t1003.001 --name "chiper coverage"
    python3 scripts/build-navigator-layer.py --from-file ids.txt --out layer.json
"""
import argparse, json, sys
from datetime import date
from pathlib import Path

def main() -> int:
    ap = argparse.ArgumentParser(description="Generate an ATT&CK Navigator layer JSON.")
    ap.add_argument("techniques", nargs="*", help="technique ids, e.g. t1059.001")
    ap.add_argument("--from-file", help="file with one technique id per line")
    ap.add_argument("--name", default="chiper-cyber layer")
    ap.add_argument("--domain", default="enterprise-attack")
    ap.add_argument("--out", help="write JSON here instead of stdout")
    args = ap.parse_args()

    ids = [t.strip().lower() for t in args.techniques]
    if args.from_file:
        try:
            ids += [l.strip().lower() for l in Path(args.from_file).read_text().splitlines()
                    if l.strip() and not l.startswith("#")]
        except OSError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 2
    ids = sorted({i for i in ids if i})
    if not ids:
        print("error: no technique ids given", file=sys.stderr)
        return 2

    layer = {
        "name": args.name,
        "versions": {"attack": "18", "navigator": "5.1.0", "layer": "4.5"},
        "domain": args.domain,
        "description": f"Generated by chiper-cyber build-navigator-layer.py on {date.today()}",
        "filters": {"platforms": []},
        "sorting": 0,
        "layout": {"layout": "side", "showID": True, "showName": True,
                   "showAggregateScores": False, "showLegend": True},
        "hideDisabled": False,
        "techniques": [{"techniqueID": t, "score": 100, "enabled": True,
                        "comment": "", "showSubtechniques": False} for t in ids],
        "gradient": {"colors": ["#ffffff", "#ff6666"], "minValue": 0, "maxValue": 100},
        "legendItems": [],
        "metadata": [{"name": "generated_by", "value": "chiper-cyber"}],
        "showTacticRowBackground": False,
        "tacticRowBackground": "#dddddd",
        "selectTechniquesAcrossTactics": True,
        "selectSubtechniquesWithParent": False,
    }
    payload = json.dumps(layer, indent=2)
    if args.out:
        try:
            Path(args.out).write_text(payload + "\n", encoding="utf-8")
        except OSError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 2
        print(f"wrote {args.out} with {len(ids)} technique(s)")
    else:
        print(payload)
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
